    upload = {"external_management_ref": "BQL-1", "external_user_id": "resident-1", "external_ticket_id": "ticket-1",
        "external_conversation_id": "chat-1", "content_type": "image/png", "size": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    response = client.post("/workforce/v1/partner/assets/uploads", headers=headers, json=upload)
    assert response.status_code == 201, response.text
    asset = response.json()
    sent = httpx.post(asset["upload_url"], data=asset["fields"], files={"file": ("evidence.png", data, "image/png")})
    assert sent.status_code in (200, 204), sent.text
    base = f"/workforce/v1/partner/assets/{asset['asset_id']}"
