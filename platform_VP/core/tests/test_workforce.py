def test_twenty_native_agent_teams_execute_concurrently(stack):
    from fake_llm import CALLS, FakeServer
    from support import DemoPack

    from awp.providers import ModelCatalog, ModelSpec
    from awp.workforce.worker import loop
    client, service, headers, route_id = stack
