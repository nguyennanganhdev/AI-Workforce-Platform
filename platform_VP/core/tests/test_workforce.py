def test_provider_signature_dedupe_early_event_and_order(stack):
    client, wf, headers, _ = stack
    response, _ = start(client, headers)
    data = response.json()
    p = client.post("/workforce/v1/admin/clients", headers=ADMIN, json={"id": "provider", "purpose": "provider",
        "operations": ["publish_job_event", "read_event_receipt"], "settings": {
            "event_map": {"job.done": {"status": "completed", "mode": "snapshot", "schema": {"type": "object", "additionalProperties": False}}},
            "transitions": {"pending": ["completed"], "completed": ["completed"]}}}).json()
    ph = {"Authorization": "ApiKey " + p["api_key"]}
    body = {"external_event_id": "event-1", "external_job_id": "job-1", "client_reference": "ref",
            "event_type": "job.done", "provider_version": 2, "occurred_at": "2026-10-10T01:00:00Z", "data": {}}
    def send(payload, valid=True):
        raw = json.dumps(payload).encode()
        ts = str(int(time.time()))
        signature = hmac.new(p["signing_secret"].encode(), ts.encode() + b"." + raw, hashlib.sha256).hexdigest()
        return client.post("/workforce/v1/provider/job-events", content=raw, headers={**ph, "Content-Type": "application/json",
            "X-Partner-Timestamp": ts, "X-Partner-Key-Id": p["signing_key_id"], "X-Partner-Signature": "v1=" + (signature if valid else "bad")})
    assert send(body, False).status_code == 401
    receipt = send(body)
    assert receipt.status_code == 202, receipt.text
    receipt_id = receipt.json()["receipt_id"]
    assert send(body).json()["duplicate"]
    assert send({**body, "data": {"invalid": True}}).status_code == 422
    assert client.portal.call(provider.apply, wf, receipt_id) is False
    async def seed():
        async with wf.tx() as conn:
            await conn.execute(insert(s.operations).values(id="op", workflow_id=data["workflow_id"], integration_id="provider",
                client_reference="ref", external_job_id="job-1", status="pending", provider_version=0, data={}, created=time.time()))
    client.portal.call(seed)
    assert client.portal.call(provider.apply, wf, receipt_id) is True
    result = client.get(receipt.json()["status_url"], headers=ph)
    assert result.json()["ingestion_status"] == "applied"
    older = send({**body, "external_event_id": "event-old", "provider_version": 1})
    client.portal.call(provider.apply, wf, older.json()["receipt_id"])
    assert client.get(older.json()["status_url"], headers=ph).json()["ingestion_status"] == "duplicate"
    bad = send({**body, "external_event_id": "event-bad", "client_reference": "wrong"})
    client.portal.call(provider.apply, wf, bad.json()["receipt_id"])
    assert client.get(bad.json()["status_url"], headers=ph).json()["ingestion_status"] == "rejected"


def test_expired_lease_cannot_spend_or_finalize(stack):
    from awp.workforce.execution import Fence, reserve
    from awp.workforce.service import Fault
    client, wf, headers, _ = stack
    response, _ = start(client, headers)
    first = client.portal.call(claim, wf, "old")
    fence = Fence(first["id"], first["owner"], first["generation"])
    async def expire():
        async with wf.tx() as conn:
            await conn.execute(update(s.jobs).where(s.jobs.c.id == first["id"]).values(lease_until=0))
    client.portal.call(expire)
    second = client.portal.call(claim, wf, "new")
    assert second["generation"] == first["generation"] + 1
    with pytest.raises(Fault, match="STALE_EXECUTION"):
        client.portal.call(reserve, wf, fence, 1, 1)
    async def stale_complete():
        return await lifecycle.complete(wf, response.json()["workflow_id"], "Stale answer", fence=fence)
    with pytest.raises(Fault, match="STALE_EXECUTION"):
        client.portal.call(stale_complete)
    new_fence = Fence(second["id"], second["owner"], second["generation"])
    client.portal.call(reserve, wf, new_fence, 100000, 500000)
    with pytest.raises(Fault, match="BUDGET_EXHAUSTED"):
        client.portal.call(reserve, wf, new_fence, 1, 1)


