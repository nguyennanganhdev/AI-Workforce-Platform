#!/usr/bin/env python3
"""Write deploy/.env from deploy/.env.example with fresh secrets. Standard library only; never overwrites a file.

    python init_env.py                    real models: you add the provider keys and edit deploy/models.yaml
    python init_env.py --demo             the scripted model and the sample MCP server (for smoke.py)
    python init_env.py --tenant acme      the tenant name of the admin key (default: main)

Generated: the admin key, AWP_SECRET_KEY (a Fernet key: 32 random bytes, url-safe base64), and the passwords of
PostgreSQL, Redis and MinIO. The admin key is printed once here; afterwards it lives only in deploy/.env.
"""
from __future__ import annotations

import argparse
import base64
import os
import re
import secrets
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def fernet_key() -> str:
    return base64.urlsafe_b64encode(os.urandom(32)).decode()


def main() -> int:
    ap = argparse.ArgumentParser(description="Write deploy/.env with fresh secrets (never overwrites an existing file).")
    ap.add_argument("--demo", action="store_true", help="scripted model on, sample MCP server at a private address allowed")
    ap.add_argument("--tenant", default="main", help="tenant of the generated admin key (default: main)")
    ap.add_argument("--out", default=str(HERE / ".env"), help="where to write (default: deploy/.env)")
    args = ap.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9_-]{1,40}", args.tenant):
        print("the tenant name may hold letters, digits, _ and - only", file=sys.stderr)
        return 2
    out = Path(args.out)
    if out.exists():
        print(f"{out} already exists: nothing was changed. Its secrets seal data in the database; to start over on "
              "purpose, move the file away yourself (and remove the volumes: the PostgreSQL password is set only once).",
              file=sys.stderr)
        return 1

    admin = "adm_" + secrets.token_urlsafe(32)
    values = {
        "__GENERATED_ADMIN_KEY__": admin,
        "__TENANT__": args.tenant,
        "__GENERATED_FERNET_KEY__": fernet_key(),
        "__GENERATED_PG_PASSWORD__": secrets.token_hex(24),  # hex: safe inside a database URL
        "__GENERATED_REDIS_PASSWORD__": secrets.token_hex(24),
        "__GENERATED_MINIO_PASSWORD__": secrets.token_hex(24),
        "__MODELS_FILE__": "./models.demo.yaml" if args.demo else "./models.yaml",
        "__DEMO_MODEL_KEY__": "demo" if args.demo else "",
        "__MCP_ALLOW_PRIVATE__": "1" if args.demo else "0",
    }
    text = (HERE / ".env.example").read_text(encoding="utf-8")
    body = text[text.rfind("# ----", 0, text.index("# 1. Secrets")):]  # the template without its how-to header
    text = (f"# deploy/.env, generated by init_env.py{' --demo' if args.demo else ''}. SECRETS: never commit, never bake "
            "into an image.\n# Meaning of every variable: deploy/.env.example.\n\n") + body
    for token, value in values.items():
        text = text.replace(token, value)
    left = sorted(set(re.findall(r"__[A-Z_]+__", text)))
    if left:
        print(f"the template has placeholders this script does not know: {left}", file=sys.stderr)
        return 2
    try:
        fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)  # O_EXCL: a file made meanwhile is not overwritten
    except FileExistsError:
        print(f"{out} already exists: nothing was changed.", file=sys.stderr)
        return 1
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    models = HERE / "models.yaml"
    example = HERE.parent / "core" / "models.example.yaml"
    if not args.demo and not models.exists() and example.is_file():
        shutil.copyfile(example, models)
        print(f"wrote {models} (a copy of core/models.example.yaml: edit it to the models you have keys for)")
    print(f"wrote {out}")
    print(f"admin key (tenant {args.tenant}), shown once: {admin}")
    if args.demo:
        print("demo: the scripted model is on and private MCP addresses are allowed. Not for production.")
    else:
        print("next: put your provider key(s) in deploy/.env (OPENAI_API_KEY=... etc.) and check deploy/models.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
